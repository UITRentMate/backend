export function getNotificationCategory(eventType: string): NotificationCategory {
  if (Object.prototype.hasOwnProperty.call(NOTIFICATION_CATEGORY_BY_EVENT, eventType)) {
    return NOTIFICATION_CATEGORY_BY_EVENT[eventType as NotificationEventType];
  }
  return NOTIFICATION_CATEGORY.SYSTEM;
}

export function getEventTypesByCategory(category: NotificationCategory): readonly string[] {
  return (Object.entries(NOTIFICATION_CATEGORY_BY_EVENT) as Array<[string, NotificationCategory]>)
    .filter(([, mappedCategory]) => mappedCategory === category)
    .map(([eventType]) => eventType);
}

